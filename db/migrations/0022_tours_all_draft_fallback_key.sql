-- مایگریشن 0022 — seed کلید فالبک «همه پیش‌نویس» (قلم ۴ موج ۱، تصمیم ۴)
--
-- مسئله: وقتی آخرین تور منتشرشده هم به پیش‌نویس برمی‌گردد/بایگانی می‌شود،
-- سایت باید بر اساس جوابِ ذخیره‌شدهٔ مدیر رفتار کند (تور نمونه یا صفحهٔ خالی)،
-- نه سیاست ثابت و نه حدس. این کلید همان جواب را نگه می‌دارد.
--
-- مقدار 'unanswered' یعنی مدیر هنوز جواب نداده؛ پنل همان لحظه از او می‌پرسد.
-- کاملاً idempotent (الگوی WHERE NOT EXISTS مثل مایگریشن 0005 و 0018)؛
-- اجرای دوباره بی‌ضرر است. هیچ ALTER/DROP ندارد.
--
-- نکتهٔ شماره‌گذاری: مایگریشن‌های 0019 تا 0021 فقط روی دیتابیس واقعی اجرا
-- شده‌اند و فایلشان در ریپو نیست؛ این فایل دنبالهٔ همان ترتیب است.

INSERT INTO site_settings (setting_key, setting_value)
SELECT 'tours.all_draft_fallback', 'unanswered'
WHERE NOT EXISTS (SELECT 1 FROM site_settings s WHERE s.setting_key = 'tours.all_draft_fallback');
